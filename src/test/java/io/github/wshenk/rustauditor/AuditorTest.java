package io.github.wshenk.rustauditor;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class AuditorTest {

    private static final String CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index";

    static final String LOCKFILE = """
            # This file is automatically @generated by Cargo.
            version = 4

            [[package]]
            name = "app"
            version = "0.1.0"
            dependencies = [
             "middle",
             "old-thing",
             "private",
             "forked",
            ]

            [[package]]
            name = "middle"
            version = "2.0.0"
            source = "registry+https://github.com/rust-lang/crates.io-index"
            checksum = "aaaa"
            dependencies = [
             "vulnerable 1.0.0",
            ]

            [[package]]
            name = "vulnerable"
            version = "1.0.0"
            source = "registry+https://github.com/rust-lang/crates.io-index"
            checksum = "bbbb"

            [[package]]
            name = "vulnerable"
            version = "1.5.0"
            source = "registry+https://github.com/rust-lang/crates.io-index"
            checksum = "cccc"

            [[package]]
            name = "old-thing"
            version = "0.3.0"
            source = "sparse+https://index.crates.io/"

            [[package]]
            name = "private"
            version = "1.0.0"
            source = "registry+https://example.com/index"
            checksum = "dddd"

            [[package]]
            name = "forked"
            version = "0.1.0"
            source = "git+https://github.com/someone/forked#0123456789abcdef"
            """;

    static final String VULN_ADVISORY = """
            ```toml
            [advisory]
            id = "RUSTSEC-2099-0001"
            package = "vulnerable"
            date = "2099-01-01"
            url = "https://example.com/advisory"
            cvss = "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H"
            aliases = ["CVE-2099-1234"]

            [versions]
            patched = [">= 1.4.0"]
            unaffected = ["< 0.5.0"]
            ```

            # Remote code execution in vulnerable

            Details here.
            """;

    static final String UNMAINTAINED_ADVISORY = """
            ```toml
            [advisory]
            id = "RUSTSEC-2099-0002"
            package = "old-thing"
            date = "2099-02-01"
            informational = "unmaintained"

            [versions]
            patched = []
            ```

            # old-thing is unmaintained
            """;

    static final String WITHDRAWN_ADVISORY = """
            ```toml
            [advisory]
            id = "RUSTSEC-2099-0003"
            package = "middle"
            date = "2099-03-01"
            withdrawn = "2099-03-02"

            [versions]
            patched = []
            ```

            # Withdrawn advisory
            """;

    @TempDir
    Path tmp;
    Path db;
    Path lock;

    @BeforeEach
    void setUp() throws IOException {
        db = tmp.resolve("advisory-db");
        write(db.resolve("crates/vulnerable/RUSTSEC-2099-0001.md"), VULN_ADVISORY);
        write(db.resolve("crates/old-thing/RUSTSEC-2099-0002.md"), UNMAINTAINED_ADVISORY);
        write(db.resolve("crates/middle/RUSTSEC-2099-0003.md"), WITHDRAWN_ADVISORY);
        write(db.resolve("crates/broken/RUSTSEC-2099-0004.md"), "not an advisory");
        lock = tmp.resolve("project/Cargo.lock");
        write(lock, LOCKFILE);
    }

    @Test
    void findsVulnerabilitiesAndHygieneProblems() throws IOException {
        AdvisoryDatabase database = AdvisoryDatabase.load(db);
        assertEquals(3, database.size());
        assertEquals(1, database.loadErrors().size());

        AuditReport report = new Auditor(database, Set.of()).audit(CargoLock.read(lock), "Cargo.lock");

        assertEquals(7, report.packageCount());
        List<Finding> vulns = report.vulnerabilities();
        assertEquals(1, vulns.size(), "only vulnerable 1.0.0 is affected; 1.5.0 is patched");
        Finding v = vulns.get(0);
        assertEquals("vulnerable 1.0.0", v.pkg().id());
        assertEquals("RUSTSEC-2099-0001", v.advisory().id());
        assertEquals("Remote code execution in vulnerable", v.message());
        assertEquals("critical", v.advisory().severity());
        assertEquals("upgrade to >= 1.4.0", v.solution());
        assertEquals(List.of("vulnerable 1.0.0", "middle 2.0.0", "app 0.1.0"), v.dependencyPath());

        List<Finding.Kind> warnings = report.warnings().stream().map(Finding::kind).toList();
        assertEquals(List.of(Finding.Kind.UNMAINTAINED, Finding.Kind.GIT_SOURCE,
                Finding.Kind.ALTERNATE_REGISTRY, Finding.Kind.MISSING_CHECKSUM), warnings);
        assertEquals(Map.of("vulnerable", List.of("1.0.0", "1.5.0")), report.duplicates());
    }

    @Test
    void ignoresByIdOrAlias() throws IOException {
        AdvisoryDatabase database = AdvisoryDatabase.load(db);
        AuditReport report = new Auditor(database, Set.of("cve-2099-1234")).audit(CargoLock.read(lock), "Cargo.lock");
        assertTrue(report.vulnerabilities().isEmpty());
        assertEquals(List.of("RUSTSEC-2099-0001"), report.ignoredAdvisories());
    }

    @Test
    void readsLockfileV1MetadataChecksums() {
        CargoLock v1 = CargoLock.parse("""
                [[package]]
                name = "foo"
                version = "1.0.0"
                source = "registry+https://github.com/rust-lang/crates.io-index"

                [metadata]
                "checksum foo 1.0.0 (registry+https://github.com/rust-lang/crates.io-index)" = "abc"
                """);
        assertEquals(1, v1.lockfileVersion());
        assertEquals("abc", v1.packages().get(0).checksum());
        assertTrue(v1.packages().get(0).isCratesIo());
    }

    @Test
    void cliExitCodesAndOutput() {
        String[] base = {"--no-fetch", "--db", db.toString(), lock.getParent().toString()};
        Result text = run(base);
        assertEquals(Main.FINDINGS, text.code);
        assertTrue(text.out.contains("error[RUSTSEC-2099-0001] vulnerable 1.0.0: Remote code execution in vulnerable"),
                text.out);
        assertTrue(text.out.contains("via:      vulnerable 1.0.0 <- middle 2.0.0 <- app 0.1.0"), text.out);
        assertTrue(text.out.contains("1 vulnerability and 4 warnings found."), text.out);

        Result json = run(concat(base, "--format", "json"));
        assertTrue(json.out.contains("\"id\": \"RUSTSEC-2099-0001\""), json.out);
        assertTrue(json.out.contains("\"score\": 9.8"), json.out);

        assertEquals(Main.OK, run(concat(base, "--ignore", "RUSTSEC-2099-0001")).code);
        assertEquals(Main.FINDINGS, run(concat(base, "--ignore", "RUSTSEC-2099-0001", "--deny-warnings")).code);
        assertEquals(Main.ERROR, run("--no-fetch", "--db", db.toString(), tmp.resolve("missing").toString()).code);
        assertEquals(Main.ERROR, run("--format", "xml").code);
    }

    @Test
    void cliReportsNotAnAdvisoryDb() {
        Result r = run("--no-fetch", "--db", tmp.toString(), lock.toString());
        assertEquals(Main.ERROR, r.code);
        assertTrue(r.err.contains("does not look like an advisory-db checkout"), r.err);
    }

    private record Result(int code, String out, String err) {
    }

    private static Result run(String... args) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        int code = Main.run(args, new PrintStream(out, true, StandardCharsets.UTF_8),
                new PrintStream(err, true, StandardCharsets.UTF_8));
        return new Result(code, out.toString(StandardCharsets.UTF_8), err.toString(StandardCharsets.UTF_8));
    }

    private static String[] concat(String[] base, String... extra) {
        String[] all = new String[base.length + extra.length];
        System.arraycopy(base, 0, all, 0, base.length);
        System.arraycopy(extra, 0, all, base.length, extra.length);
        return all;
    }

    private static void write(Path file, String content) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, content);
    }
}
